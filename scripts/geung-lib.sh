#!/usr/bin/env bash
# Shared by the Gau Geung phase-0 ledger tests — geung-a51.sh … geung-a54.sh
# (`R-P2`). Not a test runner: each script launches a real agent CLI in a
# tmux session on this machine, which is exactly what `cargo test` must never
# do, so these are run by hand and their verdicts go on the ledger rows.
#
# Everything a run produces lands in one directory under GEUNG_RUN_ROOT
# (default: $TMPDIR/geung-phase0), named after the test and the time, so a
# verdict can be re-read later with the evidence beside it.
#
# bash 3.2, which is what macOS ships. No mapfile; no empty-array expansion
# under set -u.

set -uo pipefail

GEUNG_RUN_ROOT="${GEUNG_RUN_ROOT:-${TMPDIR:-/tmp}/geung-phase0}"
# The model the launched session uses. A ledger test asks the model for one
# word; it does not need the big one.
GEUNG_MODEL="${GEUNG_MODEL:-haiku}"
# tmux pane size for the launched session. Wide enough that the TUI does not
# wrap its own chrome, tall enough that forty lines is a real excerpt.
GEUNG_COLS="${GEUNG_COLS:-140}"
GEUNG_ROWS="${GEUNG_ROWS:-42}"
# What the Claude Code TUI shows under its input box when it is waiting for
# you: the permission-mode hint ("shift+tab to cycle") on 2.1.295, "? for
# shortcuts" on older builds. If a release renames it, set this and re-run; the scripts dump the
# screen on every timeout so the new wording is in the run directory.
GEUNG_READY_RE="${GEUNG_READY_RE:-shift\+tab to cycle|\? for shortcuts}"
GEUNG_BUSY_RE="${GEUNG_BUSY_RE:-esc to interrupt}"

geung_say()  { printf '%s\n' "$*"; }
geung_hdr()  { printf '\n== %s ==\n' "$*"; }
geung_fail() { printf '  \033[31mFAIL\033[0m %s\n' "$*"; }
geung_ok()   { printf '  \033[32m ok \033[0m %s\n' "$*"; }
geung_note() { printf '  \033[33mnote\033[0m %s\n' "$*"; }

geung_repo_root() { cd "$(dirname "$0")/.." && pwd; }

# Where Claude Code keeps its home — `CLAUDE_CONFIG_DIR` relocates all of
# `~/.claude` (the docs say so; `watcher::default_home` honours it too).
geung_claude_home() { printf '%s\n' "${CLAUDE_CONFIG_DIR:-$HOME/.claude}"; }

# `~/.claude.json` — the docs are silent on whether `CLAUDE_CONFIG_DIR` moves
# it; OpenRig treats it as moving, so look there first.
geung_claude_json() {
  if [ -n "${CLAUDE_CONFIG_DIR:-}" ] && [ -f "$CLAUDE_CONFIG_DIR/.claude.json" ]; then
    printf '%s\n' "$CLAUDE_CONFIG_DIR/.claude.json"
  else
    printf '%s\n' "$HOME/.claude.json"
  fi
}

geung_sha() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -d' ' -f1
  else shasum -a 256 "$1" | cut -d' ' -f1; fi
}

geung_uuid() {
  if command -v uuidgen >/dev/null 2>&1; then uuidgen | tr 'A-Z' 'a-z'
  else python3 -I -c 'import uuid; print(uuid.uuid4())'; fi
}

# A fresh run directory: $GEUNG_RUN_ROOT/<test>-<yyyymmdd-hhmmss>.
geung_run_dir() {
  local d="$GEUNG_RUN_ROOT/$1-$(date +%Y%m%d-%H%M%S)"
  mkdir -p "$d" || { geung_fail "cannot create $d"; exit 2; }
  printf '%s\n' "$d"
}

geung_need() {
  local c
  for c in "$@"; do
    command -v "$c" >/dev/null 2>&1 || { geung_fail "$c is not installed"; exit 2; }
  done
}

# Write the launcher the tmux pane runs. It is a file, not an inline command,
# for two reasons: the exact command line is kept beside the evidence, and the
# pane strips every CLAUDE* variable before exec — this script may itself be
# running inside a Claude Code session, and a nested `claude` that inherits
# CLAUDECODE / CLAUDE_CODE_SESSION_ID is a child session, not a plain launch.
#   geung_write_launcher <file> <cwd> <cmd> [args…]
geung_write_launcher() {
  local file="$1" dir="$2"; shift 2
  local cmd="$1"; shift
  {
    printf '#!/usr/bin/env bash\n'
    printf '# generated by %s on %s\n' "$(basename "$0")" "$(date '+%Y-%m-%d %H:%M:%S')"
    printf 'for v in $(env | sed -n '"'"'s/^\\(CLAUDE[A-Za-z0-9_]*\\)=.*/\\1/p'"'"'); do unset "$v"; done\n'
    printf 'cd %q || exit 97\n' "$dir"
    # GEUNG_KEEP_SHELL=1 leaves a shell in the pane after the CLI exits —
    # what "exited to a shell" looks like, for the A54 fixture of that name.
    if [ "${GEUNG_KEEP_SHELL:-0}" = 1 ]; then printf '%q' "$(command -v "$cmd" || printf '%s' "$cmd")"
    else printf 'exec %q' "$(command -v "$cmd" || printf '%s' "$cmd")"; fi
    local a
    for a in "$@"; do printf ' %q' "$a"; done
    printf '\n'
    [ "${GEUNG_KEEP_SHELL:-0}" = 1 ] && printf 'exec bash\n'
  } > "$file"
  chmod +x "$file"
}

# Start a detached tmux session running a launcher file.
#   geung_launch <session> <launcher>
geung_launch() {
  local s="$1" launcher="$2"
  if tmux has-session -t "=$s" 2>/dev/null; then
    geung_fail "tmux session $s already exists — kill it first: tmux kill-session -t $s"
    exit 2
  fi
  tmux new-session -d -s "$s" -x "$GEUNG_COLS" -y "$GEUNG_ROWS" bash "$launcher" || {
    geung_fail "could not create tmux session $s"; exit 2; }
  tmux set-option -t "$s" status off >/dev/null 2>&1 || true
}

geung_alive() { tmux has-session -t "=$1" 2>/dev/null; }

# tmux reads `=name` as an exact session match for has-session and
# kill-session, but a *pane* target needs the window separator too: send-keys
# and capture-pane answer "can't find pane: =name" without the trailing colon.
# Found on the first run of geung-a51.sh, 2026-10-09, when no prompt was ever
# typed and every screen dump was empty.

# The visible screen, trailing blank lines dropped.
geung_screen() { tmux capture-pane -p -t "=$1:" 2>/dev/null | sed -e :a -e '/^\n*$/{$d;N;ba' -e '}'; }

# The last forty lines — the excerpt ADR-0044 reads.
geung_excerpt() { geung_screen "$1" | tail -n 40; }

# Poll until the screen matches an extended regex, or time runs out.
#   geung_wait_screen <session> <ere> <seconds>   → 0 matched, 1 timed out, 2 session gone
geung_wait_screen() {
  local s="$1" re="$2" t="$3" i=0
  while [ "$i" -lt "$t" ]; do
    geung_alive "$s" || return 2
    if geung_screen "$s" | grep -Eq -- "$re"; then return 0; fi
    sleep 1; i=$((i + 1))
  done
  return 1
}

# Poll until a file contains a match.
#   geung_wait_file <file> <ere> <seconds>
geung_wait_file() {
  local f="$1" re="$2" t="$3" i=0
  while [ "$i" -lt "$t" ]; do
    if [ -f "$f" ] && grep -Eq -- "$re" "$f"; then return 0; fi
    sleep 1; i=$((i + 1))
  done
  return 1
}

# Wait until the session itself is gone.
geung_wait_gone() {
  local s="$1" t="$2" i=0
  while [ "$i" -lt "$t" ]; do
    geung_alive "$s" || return 0
    sleep 1; i=$((i + 1))
  done
  return 1
}

# Type a line into the session: the text literally, a beat, then Enter — the
# TUI debounces input and a same-instant Enter is sometimes swallowed.
geung_type() {
  tmux send-keys -t "=$1:" -l -- "$2"
  sleep 0.5
  tmux send-keys -t "=$1:" Enter
}

geung_key() { tmux send-keys -t "=$1:" "$2"; }

# Ask Claude Code to leave, then make sure it has.
geung_exit_claude() {
  local s="$1"
  geung_alive "$s" || return 0
  geung_type "$s" "/exit"
  geung_wait_gone "$s" 8 && return 0
  tmux send-keys -t "=$s:" Enter
  geung_wait_gone "$s" 8 && return 0
  geung_note "$s did not leave on /exit — killing the session"
  tmux kill-session -t "=$s" 2>/dev/null || true
}

# Save the current screen to a file and say where.
geung_dump() {
  local s="$1" f="$2"
  geung_screen "$s" > "$f" 2>/dev/null || true
  geung_note "screen saved to $f"
}

# One-line summary at the end of every script. The word is the ledger's
# (docs/product/assumptions.md): SUPPORTED, REFUTED, or INCONCLUSIVE when the
# run did not get far enough to say.
#   geung_verdict <SUPPORTED|REFUTED|INCONCLUSIVE> <assumption> <sentence>
geung_verdict() {
  printf '\n%s %s — %s\n' "$2" "$1" "$3"
}
